export const CHAR_W = 6;
export const textWidth = (s, scale = 1) => s.length * CHAR_W * scale - scale;

export function drawText(ctx, s, x, y, colour, scale = 1) {
  ctx.fillStyle = colour;
  s = String(s).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const g = G[s[i]] || G['?'];
    for (let r = 0; r < 7; r++) {
      const bits = g[r];
      if (!bits) continue;
      for (let c = 0; c < 5; c++) if (bits & (16 >> c)) ctx.fillRect(x + (i * CHAR_W + c) * scale, y + r * scale, scale, scale);
    }
  }
}
